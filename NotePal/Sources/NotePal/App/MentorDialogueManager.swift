        case .newton:
            return newtonPhrases
        case .confucius:
            return confuciusPhrases
        case .prayerIncenseBurner:
            return []
        case .specialA:
            return specialAPhrases
        case .specialB:
            return specialBPhrases
        case .tao:
            return taoPhrases
        }
    }

